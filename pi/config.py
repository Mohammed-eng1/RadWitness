#    بالضبط ما تمنعه قواعد هذا المشروع.
def _time_limit(name: str, default: float) -> float:
    """يقرأ حدّاً زمنياً من البيئة — والقيمة غير الصالحة تسقط إلى الافتراضي."""
    try:
        v = float(_os.environ.get(name, default))
    except (TypeError, ValueError):
        return float(default)
    # قيمة صفرية أو سالبة = «بلا حدّ» وهي **ليست خياراً**: الحارس الزمني
    # الطبقة الوحيدة الباقية على حزمة الراسبري، وتعطيله يترك الجهاز يكتب على
    # البطاقة حتى ينقطع التيار فجأة (ما يفسدها — §6).
    return float(v) if v > 0 else float(default)


