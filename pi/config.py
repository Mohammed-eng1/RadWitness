#    انقلب اتجاه التحفّظ: `B` في الأُسّ، فكلما كبرت **صغر** الاحتمال وازداد
#    ادّعاء اليقين. أي أن أرضية مرتفعة تجعل الحارس **يبالغ في ثقته فيُعلن
