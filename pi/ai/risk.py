# -*- coding: utf-8 -*-
"""
risk.py — التصنيف الخماسي لمستوى الخطر على µSv/h (M1: التصنيف فقط)
==================================================================
عتبات BRIEF الثابتة. كشف الشذوذ (Welford μ+3σ) والتراجع التلقائي عند
Critical طبقةُ سلامة تأتي في M2 — هنا نصنّف فقط لتغذية حقل risk في البث.
"""
from pi.config import RISK_LOW_USVH, RISK_MED_USVH, RISK_HIGH_USVH, RISK_CRIT_USVH

# (العتبة الدنيا، الاسم، المستوى، لون الواجهة) — مرتبة تنازلياً
_RISK_TABLE = [
    (RISK_CRIT_USVH, "Critical", 4, "#dc2626"),   # أحمر
    (RISK_HIGH_USVH, "High",     3, "#ea580c"),   # برتقالي محروق
    (RISK_MED_USVH,  "Medium",   2, "#d97706"),   # كهرماني
    (RISK_LOW_USVH,  "Low",      1, "#eab308"),   # أصفر
    (0.0,            "Safe",     0, "#22c55e"),   # أخضر
]


#: 🔴 مستوى **المجهول** — ليس درجة في السلّم بل نفيٌ للسلّم كلّه.
#   لونه رمادي عمداً: أي لون من ألوان السلّم يوحي بحكم، والمجهول ليس حكماً.
UNKNOWN = {"risk": "Unknown", "lvl": None, "color": "#94a3b8"}


def classify(usvh: float, counting=True) -> dict:
    """
    يُصنّف الجرعة (µSv/h) إلى مستوى خطر واسمه ولونه.

    🔴 و`counting` **ليست وسيطاً تجميلياً**: عدّاد لا يعدّ يُعطي
    `usvh = 0.0`، والجدول يُصنّف الصفر **Safe أخضر** — أي أن الجهاز يُعلن
    المكان آمناً **لأنه لا يقيس**. وهذا أخطر انقلاب ممكن في عدّاد إشعاع:
    الصفر الناتج عن عطل لا يُميَّز عن الصفر الناتج عن نظافة المكان،
    والمشغّل يقرأ «أخضر» فيدخل.
      • `True`  → صنّف عادةً (رأى عدّات فعلاً).
      • `False` → **Unknown**: أنبوب صامت صمتاً يتجاوز اليقين الإحصائي.
      • `None`  → **Unknown**: لم يُحسم بعد (زمن غير كافٍ) — والقاعدة 6.1
        تمنع تحويل «لم أعرف» إلى شهادة سلامة.
    ⚠ والافتراضي `True` للتوافق مع المستدعين القدامى — فمن يمرّر جرعة
      محسوبة (محاكاة/تقرير) لا يعني عدّاداً ميتاً.
    """
    if counting is not True:
        return dict(UNKNOWN)
    for threshold, name, level, color in _RISK_TABLE:
        if usvh >= threshold:
            return {"risk": name, "lvl": level, "color": color}
    return {"risk": "Safe", "lvl": 0, "color": "#22c55e"}
